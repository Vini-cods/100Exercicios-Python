# Exercício 06 - Área e perímetro do retângulo
#
# Regra:
# Área = largura × altura
# Perímetro = 2 × (largura + altura)

largura = float(input("Largura: "))
altura = float(input("Altura: "))

area = largura * altura
perimetro = 2 * (largura + altura)

print(f"Área: {area}")
print(f"Perímetro: {perimetro}")
